-- ============================================================================
--  MLB Picks Pro · Configuración de seguridad de Supabase (Row Level Security)
-- ----------------------------------------------------------------------------
--  Modelo de seguridad:
--    • LECTURA  (SELECT): pública  -> cualquiera puede ver picks e historial.
--    • ESCRITURA (INSERT/UPDATE/DELETE): solo usuarios AUTENTICADOS (el dueño).
--
--  La "anon key" del cliente es pública por diseño; la seguridad real la dan
--  estas políticas RLS. Sin esto, cualquier visitante podía borrar todo.
--
--  Cómo aplicarlo:
--    1. Supabase Dashboard -> SQL Editor -> New query.
--    2. Pega TODO este archivo y ejecútalo (Run).
--    3. Authentication -> Providers -> Email: déjalo habilitado.
--    4. Authentication -> Users -> Add user: crea TU usuario (email+password).
--       (Opcional: desactiva "Allow new users to sign up" para que nadie más
--        pueda registrarse.)
-- ============================================================================

-- Asegura que las tablas existen (no-op si ya están creadas) ------------------
create table if not exists public.predictions (
  id              bigint generated by default as identity primary key,
  created_at      timestamptz default now(),
  game_date       date,
  away            text,
  home            text,
  venue           text,
  fav             text,
  fav_prob        numeric,
  confidence      text,
  predicted_total numeric,
  home_wp         numeric,
  away_wp         numeric,
  home_ml         text,
  away_ml         text,
  top_pick_cat    text,
  top_pick_main   text,
  top_pick_prob   numeric,
  top_pick_edge   numeric,
  all_picks_json  text,
  result          text,         -- 'win' | 'loss' | 'push' | null
  top_pick_price  numeric,      -- cuota americana a la que se "apostó"
  top_pick_fair   numeric,      -- prob. justa del mercado (sin vig) al apostar
  close_fair      numeric,      -- prob. justa del mercado al CIERRE (capturada luego)
  clv             numeric       -- Closing Line Value = close_fair - top_pick_fair
);

-- Por si la tabla ya existía: agrega las columnas nuevas (idempotente) ---------
alter table public.predictions add column if not exists top_pick_price numeric;
alter table public.predictions add column if not exists top_pick_fair  numeric;
alter table public.predictions add column if not exists close_fair      numeric;
alter table public.predictions add column if not exists clv             numeric;

create table if not exists public.model_weights (
  id           bigint primary key,
  weights_json text,
  train_iter   bigint
);

-- Caché del análisis COMPLETO (para restaurar desde cualquier dispositivo) -----
create table if not exists public.analysis_cache (
  game_date  text primary key,    -- fecha analizada (YYYY-MM-DD)
  payload    text,                -- JSON con games/batters/parlays/bprops
  updated_at timestamptz default now()
);

-- 1) Activar RLS --------------------------------------------------------------
alter table public.predictions     enable row level security;
alter table public.model_weights   enable row level security;
alter table public.analysis_cache  enable row level security;

-- 2) Borrar políticas previas (idempotente) -----------------------------------
drop policy if exists "cache public read"          on public.analysis_cache;
drop policy if exists "cache auth write"           on public.analysis_cache;
drop policy if exists "cache auth update"          on public.analysis_cache;
drop policy if exists "predictions public read"    on public.predictions;
drop policy if exists "predictions auth write"     on public.predictions;
drop policy if exists "predictions auth update"    on public.predictions;
drop policy if exists "predictions auth delete"    on public.predictions;
drop policy if exists "weights public read"        on public.model_weights;
drop policy if exists "weights auth write"         on public.model_weights;
drop policy if exists "weights auth update"        on public.model_weights;

-- 3) predictions: lectura pública, escritura solo autenticado -----------------
create policy "predictions public read"
  on public.predictions for select
  using (true);

create policy "predictions auth write"
  on public.predictions for insert
  to authenticated
  with check (true);

create policy "predictions auth update"
  on public.predictions for update
  to authenticated
  using (true) with check (true);

create policy "predictions auth delete"
  on public.predictions for delete
  to authenticated
  using (true);

-- 4) model_weights: lectura pública, escritura solo autenticado ---------------
create policy "weights public read"
  on public.model_weights for select
  using (true);

create policy "weights auth write"
  on public.model_weights for insert
  to authenticated
  with check (true);

create policy "weights auth update"
  on public.model_weights for update
  to authenticated
  using (true) with check (true);

-- 5) analysis_cache: lectura pública, escritura solo autenticado ---------------
create policy "cache public read"
  on public.analysis_cache for select
  using (true);

create policy "cache auth write"
  on public.analysis_cache for insert
  to authenticated
  with check (true);

create policy "cache auth update"
  on public.analysis_cache for update
  to authenticated
  using (true) with check (true);

