-- ============================================================================
--  MLB Picks Pro · Configuración de seguridad de Supabase (Row Level Security)
-- ----------------------------------------------------------------------------
--  Modelo de seguridad:
--    • LECTURA  (SELECT): pública  -> cualquiera puede ver picks e historial.
--    • ESCRITURA (INSERT/UPDATE/DELETE): solo usuarios AUTENTICADOS (el dueño).
--
--  La "anon key" del cliente es pública por diseño; la seguridad real la dan
--  estas políticas RLS. Sin esto, cualquier visitante podía borrar todo.
--
--  Cómo aplicarlo:
--    1. Supabase Dashboard -> SQL Editor -> New query.
--    2. Pega TODO este archivo y ejecútalo (Run).
--    3. Authentication -> Providers -> Email: déjalo habilitado.
--    4. Authentication -> Users -> Add user: crea TU usuario (email+password).
--       (Opcional: desactiva "Allow new users to sign up" para que nadie más
--        pueda registrarse.)
-- ============================================================================

