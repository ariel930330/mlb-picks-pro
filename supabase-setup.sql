-- SEÑALES · historial del tablero de convicción -------------------------------
--  Una fila por juego analizado con su Edge Read (equipo señalado, tier, convicción
--  efectiva, data quality, mejor aplicación). Después se califica desde el marcador
--  final: ML del equipo señalado y F5. La clave es (game_date, game_pk), así que los
--  doubleheaders se guardan y califican por separado.
create table if not exists public.signals (
  id              bigint generated by default as identity primary key,
  created_at      timestamptz default now(),
  game_date       date,
  game_pk         bigint,
  away            text,
  home            text,
  venue           text,
  edge_team       text,      -- equipo con la ventaja según el tablero
  tier            text,      -- 'NO EDGE' | 'LEAN' | 'STRONG' | 'ELITE'
  conv_eff        numeric,   -- convicción ya atenuada por Data Quality
  net_abs         numeric,   -- convicción bruta (sin atenuar)
  net             numeric,   -- signo: + = ventaja del LOCAL
  dq              integer,   -- Data Quality 0-100
  park_pts        numeric,   -- lectura de park/weather (puntos de total)
  best_bet        text,      -- mejor aplicación sugerida (F5 / Team Total / ML / RL)
  edge_wp         numeric,   -- prob. del MODELO para el equipo señalado (¿coinciden?)
  predicted_total numeric,
  lines_json      text,      -- las 10 categorías del Edge Read
  flags_json      text,      -- red flags, conflictos y notas de DQ
  home_score      integer,
  away_score      integer,
  f5_home         integer,
  f5_away         integer,
  result          text,      -- ML del equipo señalado: 'win' | 'loss' | 'push' | null
  f5_result       text       -- F5 del equipo señalado: 'win' | 'loss' | 'push' | null
);
-- Mercado que recomendó el tablero, normalizado para poder calificarlo. Es lo ÚNICO
-- que se califica: si el tablero dijo F5, se mide F5 y no el ML. 'Team Total Over' es
-- el único que necesita guardar su línea, porque el texto del tablero no la lleva.
alter table public.signals add column if not exists best_mkt  text;      -- 'ML' | 'F5' | 'TT' | 'RL'
alter table public.signals add column if not exists best_line numeric;   -- línea del team total (solo TT)

create unique index if not exists signals_game on public.signals (game_date, game_pk);
create index if not exists signals_tier on public.signals (tier);

alter table public.signals enable row level security;
drop policy if exists "signals public read" on public.signals;
